/** True only for absolute http(s) URLs — blocks javascript:, data:, file:, etc. */
export function isSafeHttpUrl(value: string | undefined | null): boolean {
  const raw = String(value ?? '').trim();
  if (!raw) return false;
  try {
    const url = new URL(raw);
    return (url.protocol === 'https:' || url.protocol === 'http:') && Boolean(url.hostname);
  } catch {
    return false;
  }
}

const boundedText = (max: number) => z.string().trim().max(max);
const optionalText = (max: number) =>
  z.preprocess(
    (value) => (typeof value === 'string' && value.trim() === '' ? undefined : value),
    boundedText(max).optional()
  );

const optionalHttpUrl = (max = 2048) =>
  z.preprocess(
    (value) => (typeof value === 'string' && value.trim() === '' ? undefined : value),
    boundedText(max)
      .refine((value) => isSafeHttpUrl(value), 'URL must be an absolute http(s) address')
      .optional()
  );

const requiredHttpUrl = (message: string) =>
  boundedText(2048).refine((value) => isSafeHttpUrl(value), message);

const hexColor = boundedText(7).regex(/^#[0-9a-fA-F]{6}$/, 'Use a six-digit hex colour such as #2459A6');

export const emailMetricSchema = z.object({
  label: z.string().trim().min(1, 'Metric label is required').max(80),
  /** Operator-supplied measurements. Never derived or generated by AI. */
  before: optionalText(40),
  after: optionalText(40),
  value: optionalText(40),
  unit: optionalText(20),
  improvement: optionalText(40),
  note: optionalText(160),
});
export type EmailMetric = z.infer<typeof emailMetricSchema>;

const contentCardSchema = z.object({
  type: z.literal('content'),
  title: optionalText(160),
  greeting: optionalText(200),
  paragraphs: z.array(z.string().trim().min(1).max(6000)).min(1).max(12),
  bullets: z
    .array(
      z.object({
        title: optionalText(120),
        text: z.string().trim().min(1).max(1000),
      })
    )
    .max(8)
    .optional(),
  callout: optionalText(600),
});

const metricsCardSchema = z.object({
  type: z.literal('metrics'),
  title: boundedText(160).optional(),
  subtitle: optionalText(300),
  metrics: z.array(emailMetricSchema).min(1).max(6),
  /**
   * Provenance is mandatory. Metrics must come from the operator's own audit
   * or reporting; a card without a source can never be sent.
   */
  source: z.string().trim().min(3, 'A metric source is required').max(220),
});

const insightCardSchema = z.object({
  type: z.literal('insight'),
  title: boundedText(160).optional(),
  body: z.string().trim().min(1).max(2000),
  source: optionalText(220),
});

const ctaCardSchema = z.object({
  type: z.literal('cta'),
  eyebrow: optionalText(60),
  headline: z.string().trim().min(1).max(200),
  body: optionalText(800),
  buttonLabel: z.string().trim().min(1).max(48),
  buttonUrl: requiredHttpUrl('CTA destination must be an absolute http(s) URL'),
  footnote: optionalText(300),
});

const dividerCardSchema = z.object({ type: z.literal('divider') });

export const emailCardSchema = z.discriminatedUnion('type', [
  contentCardSchema,
  metricsCardSchema,
  insightCardSchema,
  ctaCardSchema,
  dividerCardSchema,
]);
export type EmailCard = z.infer<typeof emailCardSchema>;

export const emailSignatureSchema = z.object({
  name: z.string().trim().min(1, 'A signature name is required').max(120),
  title: optionalText(120),
  company: optionalText(120),
  email: z.preprocess(
    (value) => (typeof value === 'string' && value.trim() === '' ? undefined : value),
    z.string().trim().email().optional()
  ),
  phone: optionalText(40),
  website: optionalHttpUrl(300),
  note: optionalText(300),
});
export type EmailSignature = z.infer<typeof emailSignatureSchema>;

export const emailDesignDocumentSchema = z.object({
  version: z.literal(1).default(1),
  palette: z.object({ accent: hexColor.optional() }).optional(),
  header: z.object({
    label: z.string().trim().min(1).max(48).default('CORRESPONDENCE'),
    title: z.string().trim().min(1).max(160),
    subtitle: optionalText(320),
    reference: optionalText(80),
  }),
  preheader: optionalText(200),
  cards: z.array(emailCardSchema).min(1, 'Add at least one content card').max(12),
  signature: emailSignatureSchema,
  footer: z
    .object({
      reason: optionalText(400),
      postalAddress: optionalText(300),
      unsubscribeUrl: optionalHttpUrl(2048),
    })
    .optional(),
});
export type EmailDesignDocument = z.infer<typeof emailDesignDocumentSchema>;

/** Values substituted for {{placeholders}} at render time (never inside metrics). */
export interface EmailDesignVariables {
  companyName?: string;
  recipientName?: string;
  senderName?: string;
  senderTitle?: string;
  service?: string;
}

/** A metric is complete only when the operator has supplied a real measurement. */
export function metricHasValue(metric: EmailMetric): boolean {
  return Boolean(metric.before || metric.after || metric.value || metric.improvement);
}

export interface DesignValidationIssue {
  cardIndex: number;
  message: string;
}

/**
 * Checks that can only be evaluated at send time. Preview deliberately allows
 * incomplete metrics (so an operator can see the layout), but a send with an
 * empty or unsourced metric would misrepresent data, so it is blocked.
 */
export function collectSendBlockingIssues(design: EmailDesignDocument): DesignValidationIssue[] {
  const issues: DesignValidationIssue[] = [];
  if (!design.cards.some((card) => card.type === 'cta')) {
    issues.push({ cardIndex: -1, message: 'Add a call-to-action card with a real destination URL.' });
  }
  design.cards.forEach((card, cardIndex) => {
    if (card.type !== 'metrics') return;
    card.metrics.forEach((metric) => {
      if (!metricHasValue(metric)) {
        issues.push({
          cardIndex,
          message: `Metric "${metric.label}" has no verified value. Enter the measured result or remove the metric before sending.`,
        });
      }
    });
    if (!card.source.trim()) {
      issues.push({ cardIndex, message: 'The technical metrics card has no source attribution.' });
    }
  });
  return issues;
}
